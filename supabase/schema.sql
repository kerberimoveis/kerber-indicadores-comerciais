create table if not exists public.indicadores_diarios (
  id bigint generated by default as identity primary key,
  data date not null,
  equipe text not null check (equipe in ('CANOAS', 'POA', 'POA ZS', 'VIAMÃO')),
  pre_cadastros integer not null default 0 check (pre_cadastros >= 0),
  mesas_marcadas integer not null default 0 check (mesas_marcadas >= 0),
  fechamentos integer not null default 0 check (fechamentos >= 0),
  assinaturas integer not null default 0 check (assinaturas >= 0),
  criado_em timestamptz not null default now(),
  constraint indicadores_diarios_equipe_data_unique unique (equipe, data)
);

alter table public.indicadores_diarios enable row level security;

create policy "Leitura pública dos indicadores"
on public.indicadores_diarios for select to anon, authenticated using (true);

create policy "Envio público de indicadores"
on public.indicadores_diarios for insert to anon, authenticated
with check (
  equipe in ('CANOAS', 'POA', 'POA ZS', 'VIAMÃO')
  and pre_cadastros >= 0 and mesas_marcadas >= 0
  and fechamentos >= 0 and assinaturas >= 0
);

grant select, insert on public.indicadores_diarios to anon, authenticated;
grant usage, select on sequence public.indicadores_diarios_id_seq to anon, authenticated;

-- Sem políticas públicas de UPDATE/DELETE: correções somente no painel Supabase
-- até existir uma área administrativa protegida.

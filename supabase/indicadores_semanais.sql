-- Tabela de lançamentos semanais da Kerber Imóveis
-- Execute este script no Supabase: SQL Editor > New query > Run.

create table if not exists public.indicadores_semanais (
  id bigint generated by default as identity primary key,
  equipe text not null check (equipe in ('CANOAS', 'POA', 'POA ZS', 'VIAMÃO')),
  semana_inicio date not null check (extract(isodow from semana_inicio) = 1),
  aprovados_compra integer not null default 0 check (aprovados_compra >= 0),
  aprovado_sem_condicao integer not null default 0 check (aprovado_sem_condicao >= 0),
  reprovados integer not null default 0 check (reprovados >= 0),
  created_at timestamptz not null default now(),
  constraint indicadores_semanais_equipe_semana_key unique (equipe, semana_inicio)
);

alter table public.indicadores_semanais enable row level security;

drop policy if exists "Permitir leitura de indicadores semanais" on public.indicadores_semanais;
create policy "Permitir leitura de indicadores semanais"
  on public.indicadores_semanais for select
  to anon, authenticated
  using (true);

drop policy if exists "Permitir insercao de indicadores semanais" on public.indicadores_semanais;
create policy "Permitir insercao de indicadores semanais"
  on public.indicadores_semanais for insert
  to anon, authenticated
  with check (true);

grant select, insert on public.indicadores_semanais to anon, authenticated;
grant usage, select on sequence public.indicadores_semanais_id_seq to anon, authenticated;
revoke update, delete on public.indicadores_semanais from anon, authenticated;
